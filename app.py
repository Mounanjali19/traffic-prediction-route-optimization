# ============================================================
# TIMESTAMP HELPER
# ============================================================

def make_timestamp(
    date_str,
    time_str
):
    """
    Convert date and time received from the frontend
    into the timestamp format expected by preprocessing.

    Example:

        date = 2026-08-13
        time = 18:30

    becomes:

        2026-08-13T18:30
    """

    if not date_str:

        date_str = datetime.now().strftime(
            "%Y-%m-%d"
        )

    if not time_str:

        time_str = "10:00"

    hour, minute = str(
        time_str
    ).split(":")

    return (
        f"{date_str}T"
        f"{hour.zfill(2)}:"
        f"{minute.zfill(2)}"
    )


