@app.route(
    "/api/hybrid_predict",
    methods=["POST"]
)
def hybrid_predict():

    global last_prediction
    global last_prediction_metadata

    try:

        data = request.json or {}


        # ----------------------------------------------------
        # Get user inputs
        # ----------------------------------------------------

        date = data.get(
            "date"
        )

        time = data.get(
            "time",
            "10:00"
        )

        scenario = data.get(
            "scenario",
            "normal"
        )


        # Convert date/time into the timestamp used
        # by the preprocessing pipeline.

        timestamp = make_timestamp(
            date,
            time
        )


        # ----------------------------------------------------
        # Generate model input
        # ----------------------------------------------------
        #
        # Shape:
        #
        #     (12, 30, 8)
        #
        # 12 = historical time steps
        # 30 = road segments
        # 8  = features

        sequence = generate_traffic_sequence(
            timestamp,
            scenario
        )


        # ----------------------------------------------------
        # Add batch dimension
        # ----------------------------------------------------
        #
        # Before:
        #
        #     (12, 30, 8)
        #
        # After:
        #
        #     (1, 12, 30, 8)
        #
        # The 1 represents one prediction sample.

        x = torch.tensor(
            sequence,
            dtype=torch.float32
        ).unsqueeze(0)


        # ----------------------------------------------------
        # MODEL INFERENCE
        # ----------------------------------------------------

        with torch.no_grad():

            predictions = hybrid_model(
                x,
                EDGE_INDEX
            )


        # Convert PyTorch tensor into a NumPy array.

        predictions = (
            predictions
            .detach()
            .cpu()
            .numpy()
            .flatten()
        )


        # Save the prediction for route/map requests.

        last_prediction = predictions.copy()

        last_prediction_metadata = {

            "timestamp": timestamp,

            "scenario": scenario,

            "date": date,

            "time": time

        }


        # Create readable road names.

        roads = [
            f"R{i}"
            for i in range(
                len(predictions)
            )
        ]


        return jsonify({

            "roads": roads,

            "speeds":
                predictions.tolist(),

            "unit": "km/h",

            "date": date,

            "time": time,

            "scenario": scenario

        })


    except Exception as e:

        return jsonify({

            "error": str(e)

        }), 500


