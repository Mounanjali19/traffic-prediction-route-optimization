@app.route(
    "/api/route",
    methods=["POST"]
)
def recommend_route():

    global last_prediction
    global last_prediction_metadata

    try:

        data = request.json or {}


        # ----------------------------------------------------
        # Read route request
        # ----------------------------------------------------

        start = int(
            data["start"]
        )

        end = int(
            data["end"]
        )

        date = data.get(
            "date"
        )

        time = data.get(
            "time",
            "10:00"
        )

        scenario = data.get(
            "scenario",
            "normal"
        )


        timestamp = make_timestamp(
            date,
            time
        )


        # ----------------------------------------------------
        # Reuse prediction if possible
        # ----------------------------------------------------

        predictions = None


        if (
            last_prediction is not None
            and last_prediction_metadata is not None
        ):

            if (
                last_prediction_metadata["timestamp"]
                == timestamp
                and
                last_prediction_metadata["scenario"]
                == scenario
            ):

                predictions = (
                    last_prediction.copy()
                )


        # ----------------------------------------------------
        # Generate prediction if one does not exist
        # ----------------------------------------------------

        if predictions is None:

            sequence = generate_traffic_sequence(
                timestamp,
                scenario
            )


            x = torch.tensor(
                sequence,
                dtype=torch.float32
            ).unsqueeze(0)


            with torch.no_grad():

                predictions = (
                    hybrid_model(
                        x,
                        EDGE_INDEX
                    )
                    .detach()
                    .cpu()
                    .numpy()
                    .flatten()
                )


        # ----------------------------------------------------
        # Validate road indices
        # ----------------------------------------------------

        number_of_roads = len(
            predictions
        )


        if (
            start < 0
            or end < 0
            or start >= number_of_roads
            or end >= number_of_roads
        ):

            return jsonify({

                "error":
                    f"Road indices must be "
                    f"between 0 and "
                    f"{number_of_roads - 1}"

            }), 400


        # ----------------------------------------------------
        # Define candidate corridor
        # ----------------------------------------------------

        low = min(
            start,
            end
        )

        high = max(
            start,
            end
        )


        candidate_speeds = predictions[
            low:high + 1
        ]


        # ----------------------------------------------------
        # Select the road with the highest predicted speed
        # ----------------------------------------------------

        local_index = int(
            np.argmax(
                candidate_speeds
            )
        )


        recommended_index = (
            low + local_index
        )


        recommended_speed = float(
            predictions[
                recommended_index
            ]
        )


        # Convert model index back to the original
        # road edge identifier.

        recommended_edge_id = None


        if (
            SEL_EDGES is not None
            and
            recommended_index < len(
                SEL_EDGES
            )
        ):

            recommended_edge_id = (
                SEL_EDGES[
                    recommended_index
                ]
            )


        return jsonify({

            "start": start,

            "end": end,

            "recommended_route_index":
                recommended_index,

            "recommended_edge_id":
                recommended_edge_id,

            "predicted_speed":
                recommended_speed,

            "unit": "km/h"

        })


    except Exception as e:

        return jsonify({

            "error": str(e)

        }), 500


