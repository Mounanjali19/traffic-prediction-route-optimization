@app.route(
    "/api/route_map_full",
    methods=["POST"]
)
def route_map_full():

    try:

        if last_prediction is None:

            return jsonify({

                "error":
                    "Run traffic prediction first."

            }), 400


        speeds = last_prediction


        # Load road geometry from the CSV.

        df = pd.read_csv(
            EDGE_FILE
        )


        # Center map around the
        # Electronic City / Bommasandra region.

        traffic_map = folium.Map(

            location=[
                12.8450,
                77.6600
            ],

            zoom_start=14

        )


        # ----------------------------------------------------
        # Draw predicted traffic conditions
        # ----------------------------------------------------

        for i in range(
            len(speeds)
        ):

            row = df[
                df["edge_id"]
                == SEL_EDGES[i]
            ]


            if row.empty:

                continue


            row = row.iloc[0]


            geometry = str(
                row["geometry"]
            )


            # Convert LINESTRING geometry into
            # Folium [latitude, longitude] coordinates.

            try:

                geometry_string = (
                    geometry
                    .replace(
                        "LINESTRING (",
                        ""
                    )
                    .replace(
                        ")",
                        ""
                    )
                )


                coordinates = []


                for pair in (
                    geometry_string.split(",")
                ):

                    lon, lat = (
                        pair.strip().split()
                    )


                    coordinates.append([

                        float(lat),

                        float(lon)

                    ])


            except Exception:

                continue


            speed = float(
                speeds[i]
            )


            # Simple traffic visualization.

            if speed >= 25:

                color = "green"

            elif speed >= 18:

                color = "orange"

            else:

                color = "red"


            folium.PolyLine(

                coordinates,

                color=color,

                weight=5,

                tooltip=(
                    f"Road R{i} | "
                    f"Predicted speed: "
                    f"{speed:.2f} km/h"
                )

            ).add_to(
                traffic_map
            )


        # ----------------------------------------------------
        # Highlight fastest predicted road
        # ----------------------------------------------------

        best_index = int(
            np.argmax(
                speeds
            )
        )


        best_row = df[
            df["edge_id"]
            == SEL_EDGES[
                best_index
            ]
        ]


        if not best_row.empty:

            best_row = (
                best_row.iloc[0]
            )


            geometry = str(
                best_row["geometry"]
            )


            try:

                geometry_string = (
                    geometry
                    .replace(
                        "LINESTRING (",
                        ""
                    )
                    .replace(
                        ")",
                        ""
                    )
                )


                best_coordinates = []


                for pair in (
                    geometry_string.split(",")
                ):

                    lon, lat = (
                        pair.strip().split()
                    )


                    best_coordinates.append([

                        float(lat),

                        float(lon)

                    ])


                folium.PolyLine(

                    best_coordinates,

                    color="blue",

                    weight=7,

                    tooltip=(
                        f"Recommended road: "
                        f"R{best_index} | "
                        f"{speeds[best_index]:.2f} km/h"
                    )

                ).add_to(
                    traffic_map
                )


            except Exception:

                pass


        # ----------------------------------------------------
        # Save generated map
        # ----------------------------------------------------

        map_directory = os.path.join(

            BASE_DIR,

            "static",

            "maps"

        )


        os.makedirs(
            map_directory,
            exist_ok=True
        )


        map_path = os.path.join(

            map_directory,

            "traffic_full.html"

        )


        traffic_map.save(
            map_path
        )


        return jsonify({

            "map_url":
                "/static/maps/traffic_full.html"

        })


    except Exception as e:

        return jsonify({

            "error": str(e)

        }), 500


